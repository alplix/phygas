"""Generates src/phygas_kernel_cl.inc: the OpenCL C source of the Phygas kernels as a C string literal
(an OpenCL prelude + src/phygas_kernel_body.h, the same device code the CUDA backend compiles).
Run after editing phygas_kernel_body.h:  python scripts/embed_kernel.py"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "src")
prelude = """#pragma OPENCL EXTENSION cl_khr_fp64 : enable
#pragma OPENCL FP_CONTRACT OFF
#define PG_GLOBAL __global
#define PG_DEVICE
#define PG_KERNEL __kernel
#define PG_TID ((int)get_global_id(0))
#define PG_U64 ulong
#define PG_LONG long
#define PG_INF (as_double((ulong)0x7ff0000000000000UL))
"""
body = open(os.path.join(src, "phygas_kernel_body.h"), encoding="utf-8").read()
lines = (prelude + body).splitlines()
out = ["// GENERATED by scripts/embed_kernel.py from phygas_kernel_body.h -- do not edit by hand.",
       "static const char *kPhygasKernelCL ="]
for ln in lines:
    out.append('    "' + ln.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
out[-1] += ";"
open(os.path.join(src, "phygas_kernel_cl.inc"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote src/phygas_kernel_cl.inc,", len(lines), "lines")
